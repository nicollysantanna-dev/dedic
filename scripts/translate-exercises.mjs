const capitalize = (text) => text.charAt(0).toUpperCase() + text.slice(1)
const normalize = (name) =>
  name.toLowerCase().replace(/\(|\)/g, ' ').replace(/-/g, ' ').replace(/\s+/g, ' ').trim()

function translate(rawName) {
  const normalized = normalize(rawName)
  if (overrides[normalized]) return overrides[normalized]

  let remaining = ` ${normalized} `
  let movement = null
  for (const [en, pt] of movements) {
    const needle = ` ${en} `
    if (remaining.includes(needle)) {
      movement = pt
      remaining = remaining.replace(needle, ' ')
      break
    }
  }
  if (!movement) return null

  const parts = { position: [], grip: [], equipment: [], extra: [] }
  for (const [en, pt, slot] of modifiers) {
    const needle = ` ${en} `
    while (remaining.includes(needle)) {
      remaining = remaining.replace(needle, ' ')
      if (slot !== 'drop' && pt) parts[slot].push(pt)
    }
  }
  const leftover = remaining.trim()
  // Palavras não reconhecidas ficam ao final em inglês, para revisão.
  const tail = leftover ? `(${leftover})` : ''
  const sentence = [
    movement,
    ...parts.position,
    ...parts.grip,
    ...parts.extra,
    ...parts.equipment,
    tail,
  ]
    .filter(Boolean)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
  return capitalize(sentence)
}

const output = {}
let translated = 0
let withLeftover = 0
for (const exercise of exercises) {
  const name = translate(exercise.name)
  if (name) {
    translated += 1
    if (name.includes('(')) withLeftover += 1
    output[exercise.externalId] = name
  }
}
writeFileSync(
  'supabase/seed/exercises.pt-BR.json',
  JSON.stringify(output, null, 2) + '\n',
)
console.log(
  `${translated}/${exercises.length} traduzidos (${withLeftover} com termo residual em inglês)`,
)
